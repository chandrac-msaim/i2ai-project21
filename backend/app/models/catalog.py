"""B. Calendar and catalog."""
from datetime import date, datetime, time
from decimal import Decimal

from pgvector.sqlalchemy import Vector
from sqlalchemy import (
    ARRAY,
    CHAR,
    Boolean,
    Computed,
    Date,
    DateTime,
    ForeignKey,
    ForeignKeyConstraint,
    Integer,
    Numeric,
    Text,
    Time,
    text,
)
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.models.base import Base


class Term(Base):
    __tablename__ = "terms"

    term_code: Mapped[str] = mapped_column(Text, primary_key=True)
    season: Mapped[str] = mapped_column(Text)
    year: Mapped[int] = mapped_column(Integer)
    seq: Mapped[int] = mapped_column(Integer, unique=True)
    start_date: Mapped[date | None] = mapped_column(Date)
    end_date: Mapped[date | None] = mapped_column(Date)
    is_current: Mapped[bool] = mapped_column(Boolean, server_default=text("false"))
    registration_opens: Mapped[date] = mapped_column(Date)
    registration_closes: Mapped[date] = mapped_column(Date)


class TermSession(Base):
    __tablename__ = "term_sessions"

    term_code: Mapped[str] = mapped_column(Text, ForeignKey("terms.term_code"), primary_key=True)
    session_code: Mapped[str] = mapped_column(Text, primary_key=True)
    start_date: Mapped[date] = mapped_column(Date)
    end_date: Mapped[date] = mapped_column(Date)


class Subject(Base):
    __tablename__ = "subjects"

    subject_code: Mapped[str] = mapped_column(Text, primary_key=True)
    name: Mapped[str | None] = mapped_column(Text)
    is_home_college: Mapped[bool] = mapped_column(Boolean, server_default=text("false"))


class CourseType(Base):
    __tablename__ = "course_types"

    type_code: Mapped[str] = mapped_column(Text, primary_key=True)
    name: Mapped[str] = mapped_column(Text, unique=True)
    needs_approval: Mapped[bool] = mapped_column(Boolean, server_default=text("false"))


class Course(Base):
    __tablename__ = "courses"

    course_code: Mapped[str] = mapped_column(Text, primary_key=True)
    subject_code: Mapped[str] = mapped_column(Text, ForeignKey("subjects.subject_code"))
    course_number: Mapped[int] = mapped_column(Integer)
    title: Mapped[str] = mapped_column(Text)
    description: Mapped[str | None] = mapped_column(Text)
    type_code: Mapped[str | None] = mapped_column(Text, ForeignKey("course_types.type_code"))
    units_type: Mapped[str] = mapped_column(Text, server_default=text("'fixed'"))
    units_default: Mapped[Decimal | None] = mapped_column(Numeric(4, 1))
    units_min: Mapped[Decimal | None] = mapped_column(Numeric(4, 1))
    units_max: Mapped[Decimal | None] = mapped_column(Numeric(4, 1))
    units_note: Mapped[str | None] = mapped_column(Text)
    # Generated by PostgreSQL, read-only
    level: Mapped[str | None] = mapped_column(
        Text,
        Computed("CASE WHEN course_number < 600 THEN 'undergraduate' ELSE 'graduate' END", persisted=True),
    )
    prereq_text: Mapped[str | None] = mapped_column(Text)
    typical_offering: Mapped[str | None] = mapped_column(Text)
    in_catalog: Mapped[bool] = mapped_column(Boolean, server_default=text("true"))
    syllabus_url: Mapped[str | None] = mapped_column(Text)
    embedding: Mapped[list[float] | None] = mapped_column(Vector(384))
    embedded_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    course_type: Mapped["CourseType | None"] = relationship()


class CoursePrerequisite(Base):
    """OR-of-ANDs: satisfied when all rows of any one option_no are satisfied."""

    __tablename__ = "course_prerequisites"

    course_code: Mapped[str] = mapped_column(
        Text, ForeignKey("courses.course_code", ondelete="CASCADE"), primary_key=True
    )
    option_no: Mapped[int] = mapped_column(Integer, primary_key=True)
    required_course_code: Mapped[str] = mapped_column(
        Text, ForeignKey("courses.course_code"), primary_key=True
    )


class CourseCorequisite(Base):
    __tablename__ = "course_corequisites"

    course_code: Mapped[str] = mapped_column(
        Text, ForeignKey("courses.course_code", ondelete="CASCADE"), primary_key=True
    )
    coreq_course_code: Mapped[str] = mapped_column(Text, ForeignKey("courses.course_code"), primary_key=True)


class CourseOffering(Base):
    __tablename__ = "course_offerings"

    course_code: Mapped[str] = mapped_column(Text, ForeignKey("courses.course_code"), primary_key=True)
    term_code: Mapped[str] = mapped_column(Text, ForeignKey("terms.term_code"), primary_key=True)
    status: Mapped[str] = mapped_column(Text)
    active_sections: Mapped[int] = mapped_column(Integer, server_default=text("0"))
    course_length: Mapped[str | None] = mapped_column(Text)
    syllabus_url: Mapped[str | None] = mapped_column(Text)
    is_assumed: Mapped[bool] = mapped_column(Boolean, server_default=text("false"))


class Instructor(Base):
    __tablename__ = "instructors"

    instructor_id: Mapped[int] = mapped_column(Integer, primary_key=True)
    full_name: Mapped[str] = mapped_column(Text, unique=True)
    email: Mapped[str | None] = mapped_column(Text, unique=True)
    profile_url: Mapped[str | None] = mapped_column(Text)
    bio: Mapped[str | None] = mapped_column(Text)
    teaching_since: Mapped[int | None] = mapped_column(Integer)
    is_synthetic: Mapped[bool] = mapped_column(Boolean, server_default=text("false"))


class Section(Base):
    __tablename__ = "sections"
    __table_args__ = (
        ForeignKeyConstraint(
            ["course_code", "term_code"], ["course_offerings.course_code", "course_offerings.term_code"]
        ),
        ForeignKeyConstraint(
            ["term_code", "session_code"], ["term_sessions.term_code", "term_sessions.session_code"]
        ),
    )

    section_id: Mapped[str] = mapped_column(Text, primary_key=True)
    course_code: Mapped[str] = mapped_column(Text)
    term_code: Mapped[str] = mapped_column(Text)
    section_code: Mapped[str] = mapped_column(Text)
    session_code: Mapped[str] = mapped_column(Text)
    modality: Mapped[str] = mapped_column(Text)
    location: Mapped[str | None] = mapped_column(Text)
    status: Mapped[str] = mapped_column(Text)
    capacity: Mapped[int | None] = mapped_column(Integer)
    enrolled: Mapped[int] = mapped_column(Integer, server_default=text("0"))
    waitlisted: Mapped[int] = mapped_column(Integer, server_default=text("0"))
    # Generated by PostgreSQL, read-only
    seats_left: Mapped[int | None] = mapped_column(
        Integer, Computed("GREATEST(capacity - enrolled, 0)", persisted=True)
    )
    is_time_tba: Mapped[bool] = mapped_column(Boolean, server_default=text("false"))
    days_times_raw: Mapped[str | None] = mapped_column(Text)
    synthetic_fields: Mapped[list[str]] = mapped_column(ARRAY(Text), server_default=text("'{}'"))

    meetings: Mapped[list["SectionMeeting"]] = relationship(
        back_populates="section", order_by="SectionMeeting.day_of_week"
    )
    session: Mapped["TermSession"] = relationship(viewonly=True)


class SectionMeeting(Base):
    __tablename__ = "section_meetings"

    section_id: Mapped[str] = mapped_column(
        Text, ForeignKey("sections.section_id", ondelete="CASCADE"), primary_key=True
    )
    day_of_week: Mapped[str] = mapped_column(CHAR(1), primary_key=True)
    start_time: Mapped[time] = mapped_column(Time, primary_key=True)
    end_time: Mapped[time] = mapped_column(Time)

    section: Mapped["Section"] = relationship(back_populates="meetings")


class SectionInstructor(Base):
    __tablename__ = "section_instructors"

    section_id: Mapped[str] = mapped_column(
        Text, ForeignKey("sections.section_id", ondelete="CASCADE"), primary_key=True
    )
    instructor_id: Mapped[int] = mapped_column(
        Integer, ForeignKey("instructors.instructor_id"), primary_key=True
    )


class CourseTermStat(Base):
    __tablename__ = "course_term_stats"

    course_code: Mapped[str] = mapped_column(Text, ForeignKey("courses.course_code"), primary_key=True)
    term_code: Mapped[str] = mapped_column(Text, ForeignKey("terms.term_code"), primary_key=True)
    capacity: Mapped[int] = mapped_column(Integer)
    enrolled: Mapped[int] = mapped_column(Integer)
    waitlist_peak: Mapped[int] = mapped_column(Integer, server_default=text("0"))
    hours_to_fill: Mapped[Decimal | None] = mapped_column(Numeric(6, 1))
    source: Mapped[str] = mapped_column(Text, server_default=text("'synthetic'"))
